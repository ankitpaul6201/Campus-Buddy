import React, { useState } from 'react';
import { motion } from 'framer-motion';
import { MAP_PINS } from '../data/mockData';
import { MapLocationPin } from '../types';
import indiaDottedData from '../data/indiaDottedMap.json';

interface IndiaMapProps {
  onSelectPin?: (pin: MapLocationPin) => void;
  selectedCollege?: string;
}

export const IndiaMap: React.FC<IndiaMapProps> = ({ onSelectPin }) => {
  const [activePin, setActivePin] = useState<string | null>(null);
  const [clickedPin, setClickedPin] = useState<string | null>(null);

  // Ensure SVG has responsive classes
  const responsiveSvg = indiaDottedData.svg.replace(
    '<svg ',
    '<svg class="w-full h-full select-none overflow-visible" '
  );

  return (
    <div className="relative w-full max-w-[500px] aspect-[59/60] mx-auto select-none flex items-center justify-center p-2">
      
      {/* Subtle pale blue ambient aura behind the India map */}
      <div className="absolute inset-4 bg-gradient-to-tr from-[#EBF5FE]/70 via-[#F3F9FE]/40 to-[#E1F2FD]/50 rounded-full blur-2xl -z-10 pointer-events-none" />

      {/* Dotted Map SVG generated by dotted-map API */}
      <div
        className="w-full h-full flex items-center justify-center pointer-events-none drop-shadow-xs"
        dangerouslySetInnerHTML={{ __html: responsiveSvg }}
      />

      {/* Geographically calibrated map pins from dotted-map coordinate grid */}
      {MAP_PINS.map((pin, index) => {
        const isHovered = activePin === pin.id;
        const isClicked = clickedPin === pin.id;
        const showDetails = isHovered || isClicked;

        return (
          <div
            key={pin.id}
            style={{
              left: `${pin.xPercent}%`,
              top: `${pin.yPercent}%`,
            }}
            className="absolute -translate-x-1/2 -translate-y-full z-20 group cursor-pointer"
            onMouseEnter={() => setActivePin(pin.id)}
            onMouseLeave={() => setActivePin(null)}
            onClick={() => {
              setClickedPin((prev) => (prev === pin.id ? null : pin.id));
              if (onSelectPin) onSelectPin(pin);
            }}
          >
            {/* Pop-in Entrance Animation */}
            <motion.div
              initial={{ opacity: 0, y: -20, scale: 0.7 }}
              whileInView={{ opacity: 1, y: 0, scale: 1 }}
              viewport={{ once: true }}
              transition={{
                delay: 0.1 + index * 0.07,
                type: 'spring',
                stiffness: 260,
                damping: 18,
              }}
              className="relative flex flex-col items-center"
            >
              {/* Stylized Flat-Design Vector Location Marker matching uploaded image */}
              <div
                className={`relative filter drop-shadow-[0_14px_22px_rgba(25,29,37,0.22)] drop-shadow-[0_4px_8px_rgba(25,29,37,0.08)] transition-transform duration-300 ${
                  showDetails ? 'scale-105' : 'hover:scale-105'
                }`}
              >
                <svg
                  viewBox="0 0 100 118"
                  className="w-20 h-24 sm:w-24 sm:h-28 overflow-visible select-none"
                  xmlns="http://www.w3.org/2000/svg"
                >
                  <defs>
                    <clipPath id="uniMarkerClip">
                      <circle cx="50" cy="46" r="35.5" />
                    </clipPath>
                  </defs>

                  {/* Seamless white drop marker body with pointed bottom tip */}
                  <path
                    d="M 50 112 
                       C 43 98, 10 74, 10 46 
                       A 40 40 0 1 1 90 46 
                       C 90 74, 57 98, 50 112 Z"
                    fill="#FFFFFF"
                  />

                  {/* University image nested inside the circular frame */}
                  <image
                    href={pin.thumbnail}
                    x="14.5"
                    y="10.5"
                    width="71"
                    height="71"
                    clipPath="url(#uniMarkerClip)"
                    preserveAspectRatio="xMidYMid slice"
                  />
                </svg>
              </div>

              {/* University Name & Place Badge — ONLY visible after hovering over it or clicking on it */}
              <div
                className={`absolute bottom-full mb-3 bg-brand-btnDark text-white px-3.5 py-2 rounded-xl text-[11px] font-semibold whitespace-nowrap shadow-2xl z-30 flex items-center gap-2 border border-white/15 transition-all duration-200 ${
                  showDetails
                    ? 'opacity-100 scale-100 translate-y-0 pointer-events-auto'
                    : 'opacity-0 scale-95 translate-y-2 pointer-events-none'
                }`}
              >
                <span className="w-2 h-2 rounded-full bg-brand-orange animate-pulse shrink-0" />
                <div className="flex flex-col text-left leading-tight">
                  <span className="font-bold text-white text-[11.5px]">{pin.name}</span>
                  <span className="text-[#9DD6FA] text-[10px] font-normal">{pin.collegeCount}</span>
                </div>
                <div className="absolute top-full left-1/2 -translate-x-1/2 border-[5px] border-transparent border-t-brand-btnDark" />
              </div>
            </motion.div>
          </div>
        );
      })}
    </div>
  );
};
